#!/usr/bin/env python3
"""portgen.py: turn game.json into the C the generic runtime needs (Ami-Go port kit).

  portgen.py init [--force]      write /w/game.json from gates/G0/MEMMAP.md (BASE, ENTRY, code REGIONs)
  portgen.py gen OUTDIR          write OUTDIR/boot_gen.c (memory image, start registers, chipset values,
                                 HLE table, title) and OUTDIR/gamedata.c (files for run-time loads)
  portgen.py show                print the resolved configuration (seeds counted, Ghidra files used)

The generated files hold game data, so they stay in /w/out like every other build product.
"""
import fnmatch, glob, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import portcfg as P

REGN = ["d%d" % i for i in range(8)] + ["a%d" % i for i in range(8)]


def carray(name, data):
    out = ["static const unsigned char %s[%d] = {" % (name, max(len(data), 1))]
    if not data:
        out.append("0,")
    for j in range(0, len(data), 40):
        out.append(",".join(str(b) for b in data[j:j + 40]) + ",")
    out.append("};")
    return "\n".join(out)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen(outdir, cfg):
    os.makedirs(outdir, exist_ok=True)
    L = ["/* generated by kit/amigo/port/portgen.py from game.json - do not edit; game data, private build */",
         "#include <stdint.h>", '#include "boot.h"', '#include "amiga.h"']
    segs = []
    for i, s in enumerate(cfg["segments"]):
        d = P.seg_bytes(s)
        L.append(carray("seg%d" % i, d))
        segs.append((s["addr"], i, len(d)))
    L.append("typedef struct { uint32_t addr; const uint8_t *data; uint32_t len; } bootseg_t;")
    L.append("const bootseg_t boot_segs[] = {")
    for a, i, n in segs:
        L.append("  {0x%X, seg%d, %d}," % (a, i, n))
    if not segs:
        L.append("  {0, 0, 0},")
    L.append("};")
    L.append("const int boot_nsegs = %d;" % len(segs))
    L.append("const uint16_t boot_pokes[][2] = {")
    for a, b in cfg["pokes"] or [(0, 0)]:
        L.append("  {0x%X, 0x%X}," % (a, b))
    L.append("};")
    L.append("const int boot_npokes = %d;" % len(cfg["pokes"]))
    L.append("const uint32_t boot_regs[16] = {%s};" % ", ".join("0x%X" % (cfg["regs"].get(r, 0) or 0) for r in REGN))
    L.append("const uint32_t boot_pc = 0x%X;" % cfg["entry"])
    L.append("const uint16_t boot_sr = 0x%X;" % cfg["sr"])
    L.append("const char *game_title = %s;" % cstr(cfg["title"]))
    # a WHDLoad game boots through the kit's C resload (runtime/whd.c): no image segments, files embedded
    L.append("const char *boot_whd_slave = %s;" % (cstr(os.path.basename(cfg["whdload"]["slave"])) if cfg.get("whdload") else "0"))
    # G2E10 kick: a kickemu snapshot boot loads the PLAYER'S Kickstart at run time (runtime/kickrt.c); only its place, size, CRC16 and name here
    _k = cfg.get("kick") or {}
    L.append("const uint32_t boot_kick_base = 0x%X, boot_kick_size = 0x%X; const uint16_t boot_kick_crc = 0x%X; const char *const boot_kick_name = %s;" % (
        int(str(_k.get("base", "0")), 16), int(str(_k.get("size", "0")), 16), int(str(_k.get("crc", "0")), 16), cstr(_k.get("name", ""))))
    fns = sorted({v["fn"] for v in cfg["hle"].values()})
    for f in fns:
        L.append("void %s(void);" % f)
    L.append("const hle_t hle_table[] = {")
    for pc, v in sorted(cfg["hle"].items()):
        L.append("  {0x%X, %s, %d, %s}," % (pc, v["fn"], int(v.get("cycles", 2000)), cstr(v["fn"])))
    if not cfg["hle"]:
        L.append("  {0, 0, 0, 0},")
    L.append("};")
    L.append("const int hle_count = %d;" % len(cfg["hle"]))
    # the translator's view of memory (difftest replays it so instructions and PC-relative reads see the
    # same bytes): translate_only segments, then the run-time code the harness saw (from its end-of-run RAM)
    views = [(s["addr"], P.seg_bytes(s)) for s in cfg["translate_only"]]
    obs_ranges = []
    ops, _vol = P.observed(cfg)
    rc, rs = P.path("out/port/ref/ram_chip.bin"), P.path("out/port/ref/ram_slow.bin")
    if ops and os.path.exists(rc) and os.path.exists(rs):
        chip, slow = open(rc, "rb").read(), open(rs, "rb").read()
        pcs = sorted(ops)
        a0 = prev = pcs[0]
        for a in pcs[1:] + [None]:
            if a is None or a - prev > 64:
                lo, hi = a0, prev + 10
                obs_ranges.append((lo, hi))
                if hi <= 0x80000:
                    views.append((lo, chip[lo:hi]))
                elif 0xC00000 <= lo and hi <= 0xC80000:
                    views.append((lo, slow[lo - 0xC00000:hi - 0xC00000]))
                if a is not None:
                    a0 = a
            if a is not None:
                prev = a
    for i, (a, d) in enumerate(views):
        L.append(carray("vseg%d" % i, d))
    L.append("const bootseg_t view_segs[] = {")
    for i, (a, d) in enumerate(views):
        L.append("  {0x%X, vseg%d, sizeof vseg%d}," % (a, i, i))
    if not views:
        L.append("  {0, 0, 0},")
    L.append("};")
    L.append("const int view_nsegs = %d;" % len(views))
    L.append("const uint32_t view_copies[][3] = {")
    for x in cfg["copies"] or [{"src": 0, "dst": 0, "len": 0}]:
        L.append("  {0x%X, 0x%X, 0x%X}," % (x["src"], x["dst"], x["len"]))
    L.append("};")
    L.append("const int view_ncopies = %d;" % len(cfg["copies"]))
    # difftest scratch windows: 64 KB of RAM holding no code, filled with noise for memory operands
    code = list(cfg["code"]) + obs_ranges
    free = lambda a: all(b <= a or a + 0x10000 <= s_ for s_, b in [(r[0], r[1]) for r in code])
    cw = next((a for a in range(0x10000, 0x80000, 0x10000) if free(a)), 0x70000)
    sw = next((a for a in (0xC50000, 0xC60000, 0xC40000, 0xC30000, 0xC20000, 0xC70000) if free(a)), 0)
    L.append("const uint32_t dt_win[2] = {0x%X, 0x%X};" % (cw, sw))
    if cfg.get("boot_extra"):
        L.append("void game_boot_extra(uint32_t *regs, uint32_t *pc, uint16_t *sr);")
        L.append("void boot_gen_extra(uint32_t *regs, uint32_t *pc, uint16_t *sr) { game_boot_extra(regs, pc, sr); }")
    else:
        L.append("void boot_gen_extra(uint32_t *regs, uint32_t *pc, uint16_t *sr) { (void)regs; (void)pc; (void)sr; }")
    open(os.path.join(outdir, "boot_gen.c"), "w").write("\n".join(L) + "\n")
    # files for run-time loads
    files = []
    # G2E9 nfiles (Claude sub-agent, 27 Oct 2026): game.json "files_tree" = {"dir": install folder, "curdir": the slave's ws_CurrentDir,
    # "exclude": [fnmatch]}. A native (snapshot) exe has no whd.c, so it embeds the whole install with each file named as whd.c finds it
    # for the reference: relative to CurrentDir when inside it ("FRT" for data/FRT), else relative to the install folder
    # ("sound/HERO.INS"). CurrentDir files come first (whd.c tries curdir/name before name; gamefile() returns the first match).
    # Measured: 15 games' native runs asked for install files in a subfolder that "files": ["<install>/*"] never embedded.
    ft = cfg.get("files_tree")
    if ft and os.path.isdir(P.path(ft["dir"])):
        root = P.path(ft["dir"]); cd = (ft.get("curdir") or "").strip("/"); skip = ft.get("exclude", [])
        inner, outer = [], []
        for dp, dn, fn in os.walk(root):
            dn.sort()
            for f in sorted(fn):
                rel = os.path.relpath(os.path.join(dp, f), root).replace(os.sep, "/")
                if any(fnmatch.fnmatch(rel, p) for p in skip):
                    continue
                if cd and rel.lower().startswith(cd.lower() + "/"):
                    inner.append((rel[len(cd) + 1:], os.path.join(dp, f)))
                else:
                    outer.append((rel, os.path.join(dp, f)))
        files += inner + outer
    have = {n.lower() for n, _ in files}
    for pat in cfg["files"]:
        files += [(os.path.basename(f), f) for f in sorted(glob.glob(P.path(pat))) if os.path.isfile(f) and os.path.basename(f).lower() not in have]
    if cfg.get("whdload"):   # every file of the install, named as the slave asks for it (relative to its folder)
        root = os.path.dirname(P.path(cfg["whdload"]["slave"]))
        skip = cfg["whdload"].get("exclude", [])   # fnmatch patterns (relative names) the game never loads
        for dp, dn, fn in os.walk(root):
            dn.sort()
            # G2E10 kick (EMBDIR, live kit 26 Oct): an empty folder of the install (saves/) is embedded as a "name/" marker with no data
            if dp != root and not fn and not dn:
                rel = os.path.relpath(dp, root).replace(os.sep, "/")
                if not any(fnmatch.fnmatch(rel, p) for p in skip):
                    files.append((rel + "/", None))
            for f in sorted(fn):
                rel = os.path.relpath(os.path.join(dp, f), root).replace(os.sep, "/")
                if not any(fnmatch.fnmatch(rel, p) for p in skip):
                    files.append((rel, os.path.join(dp, f)))
    G = ["/* generated by portgen.py: game files for run-time loads (private build, never distributed) */",
         "typedef struct { const char *name; const unsigned char *data; unsigned len; } gfile_t;"]
    for i, (n, f) in enumerate(files):
        G.append(carray("f%d" % i, open(f, "rb").read() if f else b"\0"))   # G2E10 kick: EMBDIR markers
    G.append("const gfile_t game_files[] = {")
    for i, (n, f) in enumerate(files):
        G.append("  {%s, f%d, %s}," % (cstr(n), i, ("sizeof f%d" % i) if f else "0"))
    if not files:
        G.append("  {0, 0, 0},")
    G.append("};")
    G.append("const int game_nfiles = %d;" % len(files))
    open(os.path.join(outdir, "gamedata.c"), "w").write("\n".join(G) + "\n")
    return len(segs), len(files)


def main():
    a = sys.argv[1:]
    if not a or a[0] not in ("init", "gen", "show"):
        print(__doc__)
        sys.exit(2)
    if a[0] == "init":
        p, made = P.init("--force" in a)
        print(("wrote " if made else "kept existing ") + p)
        return
    cfg = P.load()
    if a[0] == "gen":
        n, f = gen(a[1], cfg)
        print("boot_gen.c: %d memory segments, %d HLE routines; gamedata.c: %d files" % (n, len(cfg["hle"]), f))
    else:
        seeds, used = P.all_seeds(cfg)
        show = {k: v for k, v in cfg.items() if k not in ("_memmap",)}
        show["code"] = ["%06X-%06X" % r for r in cfg["code"]]
        show["entry"] = "%06X" % cfg["entry"]
        show["hle"] = {"%06X" % k: v for k, v in cfg["hle"].items()}
        show["seed_count"] = len(seeds)
        show["ghidra_seed_files"] = used
        print(json.dumps(show, indent=1, default=str))


if __name__ == "__main__":
    main()
