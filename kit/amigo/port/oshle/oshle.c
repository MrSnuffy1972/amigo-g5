void hle_lib(void) { osp_in(); hle_lib_body(); if (osp_booted) osp_out(); }   /* G2E9 osport mirror */
static void hle_lib_body(void) {
    const lib_t *l = 0;
    { static int warned; if (!warned && mem_rl(4) != EXEC) { warned = 1;   /* AbsExecBase: a program that overwrote it calls through 0 */
        hle_log("HLE warning: AbsExecBase ($4) is $%08X, not $%X: the program overwrote low memory\n", mem_rl(4), EXEC); } }
    for (int i = 0; i < oshle_nlibs; i++)
        if (cpu.PC < oshle_libs[i].base && cpu.PC >= oshle_libs[i].base - 6 * oshle_libs[i].slots) l = &oshle_libs[i];
    int lvo = l ? (int)cpu.PC - (int)l->base : 0;
    /* G2E9 osport: AMIGO_OSHLE_TRACE=<file> (kit-intent g52 trace, kept): every library call with its arguments and result, in the harness
     * and the native exe alike (the native exe has no hle_log). Read-only: unset = no file, no change. */
    static FILE *t52; static int t52on = -1; if (t52on < 0) { const char *e = getenv("AMIGO_OSHLE_TRACE"); t52on = 0; if (e && *e && (t52 = fopen(e, "w"))) t52on = 1; }
    uint32_t t52a0 = A[0], t52a1 = A[1], t52a6 = A[6], t52d0 = D[0], t52d1 = D[1], t52ret = t52on ? mem_rl(A[7]) : 0;
    {   /* OSHLE_ALL=1: every call on entry, emulated or not, with the stack (for finding where a run leaves the program) */
        static int all = -1; static long nall; if (all < 0) all = getenv("OSHLE_ALL") != 0;
        if (all && nall++ < 20000) hle_log("HLEALL %s %s (-$%X) D0=$%X D1=$%X A0=$%X A1=$%X A6=$%X A7=$%X [%08X %08X %08X] S=%d\n",
                         l ? l->name : "?", l ? fn_name(l->base, lvo) : "?", -lvo, D[0], D[1], A[0], A[1], A[6], A[7],
                         mem_rl(A[7]), mem_rl(A[7] + 4), mem_rl(A[7] + 8), cpu.S);
    }
    int done = 0;
    if (l) switch (l->base) {
        case EXEC: done = exec_call(lvo); break;
        case DOS: done = dos_call(lvo);
            /* Kickstart 1.3's dos.library is BCPL underneath and returns its result in D1 as well as D0; measured 14 Oct
             * on 3D World Tennis: it Opens a file and calls Read with the handle still in D1 from that */
            if (done == 1) D[1] = D[0];
            break;
        case GFX: done = graphics_call(lvo); break;
        case INTU: done = intuition_call(lvo); break;
        case MATHFFP: done = mathffp_call(lvo); break;
        case UTIL: done = utility_call(lvo); break;   /* T10 UTIL */
        case 0x2C00u: if (lvo == -0x4E || lvo == -0x5A || lvo == -0xA8) { D[0] = 0; done = 1; } break;   /* icon: Get/FreeDiskObject, ?: no icons */
        case DUMMYDEV: if (lvo == -0x42) { unsigned long long f = chip_frame_count; if (A[0]) { mem_wl(A[0], (uint32_t)(f / 50)); mem_wl(A[0] + 4, (uint32_t)(f % 50) * 20000u); } done = 1; break; }   /* EPOCH17: timer GetSysTime(A0 timeval) */
                       if (lvo == -0x1E && mem_rl(A[1] + 0x18) == TIMERUNIT) { do_io(A[1]); mem_wb(A[1] + 0x1E, mem_rb(A[1] + 0x1E) | 1); done = 1; break; }   /* EPOCH17: timer BeginIO */
                       if (lvo == -0x1E) { mem_wb(A[1] + 0x1F, 0); mem_wb(A[1] + 0x1E, mem_rb(A[1] + 0x1E) | 1); done = 1; } else if (lvo == -0x24) done = 1; break;
        case TD: if (lvo == -0x1E) { do_io(A[1]); done = 1; } else if (lvo == -0x24) done = 1; break;   /* BeginIO, AbortIO */
        case DISK: if (lvo == -0x12) { D[0] = A[1]; done = 1; } else if (lvo == -0x18) done = 1; break; /* GetUnit, GiveUnit */
        case 0x3C00u:                                                       /* ciaa.resource / ciab.resource (DSHARD, 18 Oct 2026) */
            /* F-117A (game 486) opens ciab.resource, calls AddICRVector (-6) and gives up if it returns NULL:
             * it closed dos.library and RTSed to EXIT_PC, so check 10 failed on "exited" even with the base fixed.
             * The four Kickstart 1.3 CIA vectors are AddICRVector -6, RemICRVector -$C, AbleICR -$12, SetICR -$18.
             * This HLE delivers no CIA interrupts, but the smoke boot only needs the registration to succeed.
             * AddICRVector's result is the old vector: a non-NULL dummy says "registered". */
            if (lvo == -6) { D[0] = 0; done = 1; }   /* VERIFY: AddICRVector returns 0 on success (RKM); F-117A tests BNE to retry bit 1 */
            else if (lvo == -0xC || lvo == -0x12 || lvo == -0x18) { D[0] = 0; done = 1; }
            break;
    }
    if (t52on) { fprintf(t52, "FRAME %llu CALL %s %s (-$%X) A0=$%X A1=$%X A6=$%X D0=$%X D1=$%X ret $%06X -> ", (unsigned long long)chip_frame_count, l ? l->name : "?", l ? fn_name(l->base, lvo) : "?", -lvo, t52a0, t52a1, t52a6, t52d0, t52d1, t52ret);
        if (done == 2) fprintf(t52, "PC=$%X\n", cpu.PC); else if (!done) fprintf(t52, "UNIMPLEMENTED\n"); else fprintf(t52, "RES=$%X\n", D[0]); fflush(t52); }   /* G2E9 osport trace */
    if (done == 2) return;                                              /* the call set PC itself (Supervisor ...) */
    if (!done) {
        uint32_t ra = mem_rl(A[7]) & 0xFFFFFFu;   /* TLSETTLE v1: a real call has a JSR just before its return address; anything else
                                                    * is a jump into the table or a CPU running away through low memory */
        int jsr = ra >= 6 && (mem_rw(ra - 4) == 0x4EAE || (mem_rw(ra - 2) & 0xFFF8) == 0x4E90 || (mem_rw(ra - 4) & 0xFFF8) == 0x4EA8 ||
                              (mem_rw(ra - 4) & 0xFFF8) == 0x4EB0 || mem_rw(ra - 6) == 0x4EB9 || mem_rw(ra - 4) == 0x4EBA || mem_rw(ra - 4) == 0x4EBB);
        hle_log("HLE %s %s (-$%X) not emulated (D0=$%X D1=$%X D2=$%X A0=$%X A1=$%X ret $%06X)%s\n", l ? l->name : "?",
                l ? fn_name(l->base, lvo) : "?", -lvo, D[0], D[1], D[2], A[0], A[1], mem_rl(A[7]), jsr ? " [call]" : " [wild: no JSR before the return address]");
        D[0] = 0;
        /* G0FIX (Cowork 18 Oct, Copilot): the lowest slot of a library's table reached with no JSR, after zero memory, is the CPU
         * sliding up from address 0 ($8B8 = exec - 6 * slots), never a call. RTS would pop a stray long word and slide again for the
         * rest of the run (2.4 million executed addresses on 3D Pool). Name where the program left and end the run at EXIT_PC. */
        if (!jsr && l && cpu.PC == l->base - 6 * l->slots && (mem_rw(cpu.PC) == 0 || (mem_rl(cpu.PC - 4) == 0 && mem_rl(cpu.PC - 8) == 0))) {   /* zeros before it, or the table itself cleared */
            hle_log("OSHLE RUNAWAY: PC reached $000000 after $%06X (op %04X) A7=$%06X (A7)=$%08X, slid to %s -$%X\n",
                    oshle_last_pc, oshle_last_op, A[7], mem_rl(A[7]), l->name, -lvo);
            if (pre_on && m68k_set_reg && !getenv("E25_NO_PREFAIL")) {   /* E25 prefail: a startup-sequence line before the chosen program ran away */
                hle_log("HLE startup-sequence: an earlier line ran away; the runner is abandoned and the chosen program starts (E25 prefail)\n");
                pre_force = 1; cpu.PC = pre_entry; return; }
            cpu.PC = EXIT_PC; return;
        }
    }
    rts();
}

