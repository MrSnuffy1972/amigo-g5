        if (!ssc_line(d, n, &i, out, sizeof out, w, sizeof w)) continue;
        size_t L = strlen(out); uint32_t s = alloc((uint32_t)L + 2, MEMF_CHIP); if (!s) break;
        for (size_t j = 0; j <= L; j++) mem_wb(s + (uint32_t)j, (uint8_t)out[j]);
