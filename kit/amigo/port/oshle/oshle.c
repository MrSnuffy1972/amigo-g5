static int md_cur;                                   /* the disk "in the drive": the last volume a path named */
static int md_disk(const char *s) {                  /* the disk a path's volume names, or -1 (no volume, DF0:) */
    const char *c = strchr(s, ':');
    if (!c || c == s || !oshle_ndisks) return -1;
    size_t l = (size_t)(c - s);
    for (int k = 0; k < oshle_ndisks; k++)
        if (oshle_vols[k] && strlen(oshle_vols[k]) == l && !strncasecmp(oshle_vols[k], s, l)) return k;
    return -1;
}
static const uint8_t *md_file(const char *s, const char *b, size_t *n) {   /* gamefile() that knows the disks */
    int k = md_disk(s);
    if (k >= 0 && k != md_cur) { hle_log("HLE multi-disk: %s names disk %d (%s), was disk %d: swapped, no prompt\n", s, k + 1, oshle_vols[k], md_cur + 1); md_cur = k; }
    if (k < 0) k = md_cur;
    if (k > 0 && *b) { char q[160]; snprintf(q, sizeof q, "d%d~%s", k, b); const uint8_t *d = gamefile(q, n); if (d) return d; }
    { const uint8_t *d0 = *b ? gamefile(b, n) : 0; if (d0) return d0; }
    if (*b) for (int i = 0; i < oshle_ndisks; i++) {   /* Gemini job 23: a name with no volume may live on another disk */
        char q[160]; snprintf(q, sizeof q, "d%d~%s", i, b); const uint8_t *d = i == 0 ? gamefile(b, n) : gamefile(q, n);
        if (d) { if (i != md_cur) hle_log("HLE multi-disk: %s found on disk %d, swapped, no prompt\n", s, i + 1); md_cur = i; return d; } }
    return 0;
}
