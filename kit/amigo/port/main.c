/* Ami-Go native port - frontend (generic; from the Ghosts 'n Goblins pilot).
 * Windows build: SDL2 (statically linked) window, keyboard/joystick input, 50 Hz pacing.
 * Headless build (-DNO_SDL): for tests, writes PPM frames.
 * Keys: arrows + Ctrl = joystick, all other keys = the Amiga's keys (F1-F8), F9 options menu, F10 4:3 or square
 * pixels, F11 full screen, F12 screenshot (PNG), Shift+F12 video (reccap.c). Controller: see menu.c (mapping, keyboard on Back, menu on Start, LT F-keys, right stick mouse).
 * Options: --frames N (quit after N frames), --shot FILE (save last frame as PNG/RGBA/PPM by extension),
 *          --script FILE (lines "frame keys", keys from U D L R F S or '-', or one raw-key token Knn/Pnn/Qnn: hex Amiga keycode, K tap, P down, Q up), --stats */
