static int gx_lim(uint32_t bm, int *w, int *h) { if (!bm) return 0; *w = 8 * (int)mem_rw(bm); *h = (int)mem_rw(bm + 2); return *w > 0 && *h > 0; }
static int gx_depth(uint32_t bm) { int d = (int)mem_rb(bm + 5); return d > 8 ? 8 : d; }
static uint32_t gx_plane(uint32_t bm, int p) { uint32_t a = mem_rl(bm + 8 + 4 * (uint32_t)p); return (a == 0 || a == 0xFFFFFFFFu) ? 0 : a; }
static int gx_logn[16];
static void gx_log(int k, const char *nm, uint32_t rp) { if (gx_logn[k]++ < 3) hle_log("HLE gfx %s rp $%X: drawn (EPOCH16)\n", nm, rp); }
/* pixel (x, y): cmpl = flip the planes in msk, else write pen's bits into them */
static void gx_pset(uint32_t bm, int x, int y, int pen, int msk, int cmpl) {
    int w, h; if (!gx_lim(bm, &w, &h) || x < 0 || y < 0 || x >= w || y >= h) return;
    uint32_t o = (uint32_t)y * mem_rw(bm) + (uint32_t)(x >> 3); uint8_t mk = (uint8_t)(0x80 >> (x & 7));
    for (int p = 0, d = gx_depth(bm); p < d; p++) { uint32_t pl; if (!((msk >> p) & 1) || !(pl = gx_plane(bm, p))) continue;
        uint8_t v = (uint8_t)mem_rb(pl + o); v = cmpl ? (uint8_t)(v ^ mk) : ((pen >> p) & 1) ? (uint8_t)(v | mk) : (uint8_t)(v & ~mk); mem_wb(pl + o, v); }
}
static int gx_pget(uint32_t bm, int x, int y) {
    int w, h, pen = 0; if (!gx_lim(bm, &w, &h) || x < 0 || y < 0 || x >= w || y >= h) return 0;
    uint32_t o = (uint32_t)y * mem_rw(bm) + (uint32_t)(x >> 3); uint8_t mk = (uint8_t)(0x80 >> (x & 7));
    for (int p = 0, d = gx_depth(bm); p < d; p++) { uint32_t pl = gx_plane(bm, p); if (pl && (mem_rb(pl + o) & mk)) pen |= 1 << p; }
    return pen;
}
/* row y, x0..x1, a byte at a time */
static void gx_span(uint32_t bm, int x0, int x1, int y, int pen, int msk, int cmpl) {
    int w, h; if (!gx_lim(bm, &w, &h) || y < 0 || y >= h) return;
    if (x0 < 0) x0 = 0;
    if (x1 >= w) x1 = w - 1;
    if (x0 > x1) return;
    uint32_t row = (uint32_t)y * mem_rw(bm);
    for (int p = 0, d = gx_depth(bm); p < d; p++) { uint32_t pl; if (!((msk >> p) & 1) || !(pl = gx_plane(bm, p))) continue;
        int on = (pen >> p) & 1;
        for (int x = x0; x <= x1; ) {
            uint32_t a = pl + row + (uint32_t)(x >> 3); uint8_t v = (uint8_t)mem_rb(a), mk;
            int e = (x | 7) < x1 ? (x | 7) : x1;
            mk = (uint8_t)((0xFF >> (x & 7)) & (0xFF << (7 - (e & 7)))); x = e + 1;
            mem_wb(a, cmpl ? (uint8_t)(v ^ mk) : on ? (uint8_t)(v | mk) : (uint8_t)(v & ~mk)); }
    }
}
static void gx_line(uint32_t bm, int x0, int y0, int x1, int y1, int pen, int msk, int cmpl) {
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, dy = y1 > y0 ? y1 - y0 : y0 - y1, sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1, e = dx - dy, n = 0;
    for (;;) { gx_pset(bm, x0, y0, pen, msk, cmpl); if ((x0 == x1 && y0 == y1) || ++n > 4096) break;
        int e2 = 2 * e; if (e2 > -dy) { e -= dy; x0 += sx; } if (e2 < dx) { e += dx; y0 += sy; } }
}
/* a 1-bit template (a Text glyph, BltTemplate) drawn with the RastPort's pens and mode; jw = the JAM2 cell width */
static void gx_tpl(uint32_t rp, uint32_t bm, int x, int y, int w, int h, const uint8_t *hd, uint32_t md, int mod, int off, int jw) {
    int fg = (int)mem_rb(rp + 0x19), bg = (int)mem_rb(rp + 0x1A), mode = (int)mem_rb(rp + 0x1C), msk = (int)mem_rb(rp + 0x18);
    int inv = mode & 4, cmpl = (mode & 2) != 0, jam2 = (mode & 1) && !cmpl;
    if (w > 1024) w = 1024;
    if (h > 1024) h = 1024;
    if (off < 0) off = 0;
    if (jam2) for (int r = 0; r < h; r++) gx_span(bm, x, x + (jw > w ? jw : w) - 1, y + r, inv ? fg : bg, msk, 0);
    for (int r = 0; r < h; r++) for (int b = 0; b < w; b++) {
        uint32_t i = (uint32_t)(r * mod) + (uint32_t)((off + b) >> 3);
        int bit = ((hd ? hd[i] : (uint8_t)mem_rb(md + i)) >> (7 - ((off + b) & 7))) & 1;
        if (inv && !jam2) bit ^= 1;
        if (bit) gx_pset(bm, x + b, y + r, jam2 && inv ? bg : fg, msk, cmpl);
    }
}
static void gx_text(uint32_t rp, uint32_t s, uint32_t n) {
    uint32_t bm = rp ? mem_rl(rp + 4) : 0, tf = rp ? mem_rl(rp + 0x34) : 0; if (!bm) return;
    int own = tf && mem_rl(tf + 0x22) && mem_rl(tf + 0x28);
    uint32_t cd = own ? mem_rl(tf + 0x22) : 0, cl = own ? mem_rl(tf + 0x28) : 0, sp = own ? mem_rl(tf + 0x2C) : 0, kn = own ? mem_rl(tf + 0x30) : 0;
    int lo = own ? (int)mem_rb(tf + 0x20) : TOPAZ_LO, hi = own ? (int)mem_rb(tf + 0x21) : TOPAZ_HI, mod = own ? (int)mem_rw(tf + 0x26) : TOPAZ_MOD;
    int ys = own ? (int)mem_rw(tf + 0x14) : 8, xs = own ? (int)mem_rw(tf + 0x18) : 8, base = own ? (int)mem_rw(tf + 0x1A) : TOPAZ_BASE;
    int prop = own && (mem_rb(tf + 0x17) & 0x20) && sp, tsp = (int16_t)mem_rw(rp + 0x40);
    if (ys > 64) ys = 64;
    if (n > 1024) n = 1024;
    if (hi < lo) hi = lo;
    int x = (int16_t)mem_rw(rp + 0x24), y = (int16_t)mem_rw(rp + 0x26) - base;
    for (uint32_t j = 0; j < n; j++) {
        int c = (int)mem_rb(s + j), ix = (c >= lo && c <= hi) ? c - lo : hi - lo + 1;
        if (!own && ix > TOPAZ_HI - TOPAZ_LO + 1) ix = TOPAZ_HI - TOPAZ_LO + 1;
        uint32_t loc = own ? mem_rl(cl + 4 * (uint32_t)ix) : topaz_loc[ix];
        int kx = (own && kn) ? (int16_t)mem_rw(kn + 2 * (uint32_t)ix) : 0, adv = prop ? (int16_t)mem_rw(sp + 2 * (uint32_t)ix) : xs;
        int cw = (int)(loc & 0xFFFF); if (cw > 64) cw = 64;
        gx_tpl(rp, bm, x + kx, y, cw, ys, own ? 0 : topaz_data, cd, mod, (int)(loc >> 16), adv);
        x += adv + kx + tsp;
    }
    mem_ww(rp + 0x24, (uint16_t)x);
}
static void gx_rect(uint32_t rp, int x0, int y0, int x1, int y1) {
    uint32_t bm = mem_rl(rp + 4); int mode = (int)mem_rb(rp + 0x1C);
    for (int y = y0 < 0 ? 0 : y0; y <= y1 && y < 4096; y++) gx_span(bm, x0, x1, y, (int)mem_rb(rp + 0x19), (int)mem_rb(rp + 0x18), (mode & 2) != 0);
}
static void gx_setrast(uint32_t rp, int pen) {
    uint32_t bm = mem_rl(rp + 4); int w, h; if (!gx_lim(bm, &w, &h)) return;
    uint32_t n = mem_rw(bm) * (uint32_t)h; if (n > 0x40000) n = 0x40000;
    for (int p = 0, d = gx_depth(bm); p < d; p++) { uint32_t pl = gx_plane(bm, p); if (!pl) continue;
        uint8_t v = ((pen >> p) & 1) ? 0xFF : 0; for (uint32_t j = 0; j < n; j++) mem_wb(pl + j, v); }
}
static void gx_scroll(uint32_t rp, int dx, int dy, int x0, int y0, int x1, int y1) {
    uint32_t bm = mem_rl(rp + 4); int w, h; if (!gx_lim(bm, &w, &h)) return;
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 >= w) x1 = w - 1;
    if (y1 >= h) y1 = h - 1;
    int W = x1 - x0 + 1, H = y1 - y0 + 1, bg = (int)mem_rb(rp + 0x1A), msk = (int)mem_rb(rp + 0x18); if (W <= 0 || H <= 0) return;
    uint8_t *b = malloc((size_t)W * (size_t)H); if (!b) return;
    for (int y = 0; y < H; y++) for (int x = 0; x < W; x++) b[y * W + x] = (uint8_t)gx_pget(bm, x0 + x, y0 + y);
    for (int y = 0; y < H; y++) for (int x = 0; x < W; x++) { int sx = x + dx, sy = y + dy;
        gx_pset(bm, x0 + x, y0 + y, (sx >= 0 && sx < W && sy >= 0 && sy < H) ? b[sy * W + sx] : bg, msk, 0); }
    free(b);
}
/* BltBitMap: through a buffer (an overlapping scroll is safe), the minterm with A = all ones (bit 4 + (B<<1|C) of the minterm) */
static uint32_t gx_blit(uint32_t sb, int sx, int sy, uint32_t db, int dx, int dy, int w, int h, int mt, int msk) {
    int sw, sh, dw, dh; if (!gx_lim(sb, &sw, &sh) || !gx_lim(db, &dw, &dh)) return 0;
    int d = gx_depth(sb) < gx_depth(db) ? gx_depth(sb) : gx_depth(db);
    if (sx < 0) { w += sx; dx -= sx; sx = 0; }
    if (sy < 0) { h += sy; dy -= sy; sy = 0; }
    if (dx < 0) { w += dx; sx -= dx; dx = 0; }
    if (dy < 0) { h += dy; sy -= dy; dy = 0; }
    if (sx + w > sw) w = sw - sx;
    if (dx + w > dw) w = dw - dx;
    if (sy + h > sh) h = sh - sy;
    if (dy + h > dh) h = dh - dy;
    if (w <= 0 || h <= 0) return (uint32_t)d;
    uint8_t *b = malloc((size_t)w * (size_t)h); if (!b) return (uint32_t)d;
    uint32_t sbpr = mem_rw(sb), dbpr = mem_rw(db);
    for (int p = 0; p < d; p++) { uint32_t sp = gx_plane(sb, p), dp = gx_plane(db, p); if (!((msk >> p) & 1) || !sp || !dp) continue;
        for (int y = 0; y < h; y++) for (int x = 0; x < w; x++)
            b[y * w + x] = (uint8_t)((mem_rb(sp + (uint32_t)(sy + y) * sbpr + (uint32_t)((sx + x) >> 3)) >> (7 - ((sx + x) & 7))) & 1);
        for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
            uint32_t a = dp + (uint32_t)(dy + y) * dbpr + (uint32_t)((dx + x) >> 3); uint8_t v = (uint8_t)mem_rb(a), mk = (uint8_t)(0x80 >> ((dx + x) & 7));
            int r = (mt >> (4 + ((b[y * w + x] << 1) | ((v & mk) != 0)))) & 1; mem_wb(a, r ? (uint8_t)(v | mk) : (uint8_t)(v & ~mk)); } }
    free(b); return (uint32_t)d;
}
static void gx_image(uint32_t rp, uint32_t im, int l, int t) {   /* intuition DrawImage: PlanePick planes from ImageData, PlaneOnOff for the rest */
    uint32_t bm = rp ? mem_rl(rp + 4) : 0; if (!bm) return;
    for (int k = 0; im && k < 32; k++, im = mem_rl(im + 16)) {
        int x0 = l + (int16_t)mem_rw(im), y0 = t + (int16_t)mem_rw(im + 2), w = (int16_t)mem_rw(im + 4), h = (int16_t)mem_rw(im + 6), d = (int16_t)mem_rw(im + 8);
        uint32_t data = mem_rl(im + 10); int pick = (int)mem_rb(im + 14), onoff = (int)mem_rb(im + 15), wpr = ((w + 15) >> 4) * 2, pi = 0;
        if (w <= 0 || h <= 0 || w > 1024 || h > 1024) continue;
        for (int p = 0, bd = gx_depth(bm); p < bd; p++) {
            if ((pick >> p) & 1) { if (pi < d && data) { uint32_t src = data + (uint32_t)(pi * wpr * h);
                    for (int y = 0; y < h; y++) for (int x = 0; x < w; x++)
                        gx_pset(bm, x0 + x, y0 + y, ((mem_rb(src + (uint32_t)(y * wpr) + (uint32_t)(x >> 3)) >> (7 - (x & 7))) & 1) << p, 1 << p, 0); }
                pi++; }
            else for (int y = 0; y < h; y++) gx_span(bm, x0, x0 + w - 1, y0 + y, ((onoff >> p) & 1) << p, 1 << p, 0);
        }
    }
}
