/* SDLActivity calls SDL_main, but this file defines SDL_MAIN_HANDLED (so Windows and headless keep a plain main): forward it.
 * stdout and stderr are piped to logcat (tag "amigo") and main gets --log. Weak: gates/G5/android_main.c, where a build links
 * it, supplies the same thing. (Cowork 17 Oct 2026: the clean-sheet native_apk builds had no SDL_main and closed at once.) */
#include <unistd.h>
#include <pthread.h>
#include <android/log.h>
int main(int argc, char **argv);
static int amigo_logfd[2];
static void *amigo_logpump(void *arg) {
    (void)arg; char buf[512], line[1024]; ssize_t n; size_t ll = 0;
    while ((n = read(amigo_logfd[0], buf, sizeof buf)) > 0)
        for (ssize_t i = 0; i < n; i++) {
            if (buf[i] == '\n' || ll == sizeof line - 1) { line[ll] = 0; __android_log_write(ANDROID_LOG_INFO, "amigo", line); ll = 0; }
            if (buf[i] != '\n') line[ll++] = buf[i];
        }
    return NULL;
}
__attribute__((weak)) int SDL_main(int argc, char *argv[]) {
    (void)argc; (void)argv;
    setvbuf(stdout, NULL, _IOLBF, 0); setvbuf(stderr, NULL, _IONBF, 0);
    if (pipe(amigo_logfd) == 0) { dup2(amigo_logfd[1], 1); dup2(amigo_logfd[1], 2); pthread_t t; if (pthread_create(&t, NULL, amigo_logpump, NULL) == 0) pthread_detach(t); }
    char *args[] = { "amigo", "--log", NULL };
    return main(2, args);
}
