int main(int argc, char **argv) {
    const char *wavpath = NULL; FILE *wav = NULL; uint32_t wavbytes = 0;
    int frames = -1, stats = 0; const char *shot = NULL, *script = NULL, *dumpdir = NULL;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--frames") && i + 1 < argc) frames = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--shot") && i + 1 < argc) shot = argv[++i];
        else if (!strcmp(argv[i], "--script") && i + 1 < argc) script = argv[++i];
        else if (!strcmp(argv[i], "--dump") && i + 1 < argc) dumpdir = argv[++i];
        else if (!strcmp(argv[i], "--stats")) stats = 1;
        else if (!strcmp(argv[i], "--wav") && i + 1 < argc) wavpath = argv[++i];
        else if (!strcmp(argv[i], "--log")) logf_ = stderr;
    }
    hle_log = logfn;
    int sframe[512]; char skeys[512][8]; int ns = 0, si = 0;
    if (script) { FILE *s = fopen(script, "r"); while (s && ns < 512 && fscanf(s, "%d %7s", &sframe[ns], skeys[ns]) == 2) ns++; if (s) fclose(s); }
    if (wavpath) { wav = fopen(wavpath, "wb"); if (wav) { uint8_t z[44] = {0}; fwrite(z, 1, 44, wav); } }
#ifndef NO_SDL
    {   /* G2E10 kick (26 Oct): a kickemu game reads the player's own Kickstart from "Kickstarts" next to the executable */
        extern const char *kick_dir; static char kd[1100]; char *bp = SDL_GetBasePath();
        if (bp) { snprintf(kd, sizeof kd, "%sKickstarts", bp); kick_dir = kd; SDL_free(bp); }
    }
#endif
    ANDROID_STEP("run_boot");
    if (run_boot()) {
        extern char kick_missing[640];
        if (kick_missing[0]) {   /* G2E10 kick: no Kickstart of the player's: say exactly what is needed */
            fprintf(stderr, "%s\n", kick_missing);
#ifndef NO_SDL
            SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_ERROR, "Kickstart ROM needed", kick_missing, NULL);
#endif
            return 1;
        }
        fprintf(stderr, "boot failed: game data missing\n"); return 1;
    }
#ifdef AMIGO_TICKPC
    if (getenv("TICKPCLOG")) tickpc_f = fopen(getenv("TICKPCLOG"), "w");
#endif
#ifndef NO_SDL
    ANDROID_STEP("SDL_Init");
    SDL_SetMainReady();
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_GAMECONTROLLER | SDL_INIT_TIMER) != 0) { fprintf(stderr, "SDL: %s\n", SDL_GetError()); return 1; }
    {   /* WHDLoad saves (high scores) live in the user's profile and are read back; AMIGO_SAVE_PROFILE=0 turns this off */
        extern const char *whd_save_dir; extern int whd_save_reload;
        const char *e = getenv("AMIGO_SAVE_PROFILE");
        if (!(e && *e == '0')) { char *p = SDL_GetPrefPath("AmiGo", game_title); if (p) { whd_save_dir = p; whd_save_reload = 1; } }
    }
    ANDROID_STEP("SDL_CreateWindow");
    SDL_Window *win = SDL_CreateWindow(game_title, SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, SCR_W * 3, SCR_H * 3, SDL_WINDOW_RESIZABLE);
    /* Present with vsync; the 50 Hz game ticks stay decoupled from the display rate by the accumulator below
     * (Karl 14 Oct: SDL GPU path; Gemini review item adopted 23:58). AMIGO_NOVSYNC=1 gives the old SDL_Delay pacing (VRR displays). */
    int vsync = !(getenv("AMIGO_NOVSYNC") && *getenv("AMIGO_NOVSYNC") == '1');
    SDL_Renderer *ren = SDL_CreateRenderer(win, -1, SDL_RENDERER_ACCELERATED | (vsync ? SDL_RENDERER_PRESENTVSYNC : 0));
    if (!ren) ren = SDL_CreateRenderer(win, -1, SDL_RENDERER_SOFTWARE);
    /* Presentation. (An earlier note here attributed "modern methods at the edges, the verified chipset model in the middle" to Karl; that was a
     * misreading, corrected 14 Oct 23:58 on Karl's word. The governing directive is claude-run/NATIVE-INTENT-SPEC.md: no chip modelling.)
     * "Sharp bilinear": the Amiga frame is scaled x3 with nearest-neighbour into a target texture, which is then
     * scaled to the window with linear filtering, so pixels stay crisp without uneven widths at any window size.
     * Default shape 4:3 as on a PAL TV (lores pixels about 16:15 wide); F10 switches to square pixels. */
    int aspect43 = !(getenv("AMIGO_SQUARE") && *getenv("AMIGO_SQUARE") == '1');
    SDL_RenderSetLogicalSize(ren, aspect43 ? SCR_W * 3 * 16 / 15 : SCR_W * 3, SCR_H * 3);
    SDL_Texture *tex = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STREAMING, SCR_W, SCR_H);
    SDL_Texture *big = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_TARGET, SCR_W * 3, SCR_H * 3);
    SDL_SetTextureScaleMode(tex, SDL_ScaleModeNearest);
    if (big) SDL_SetTextureScaleMode(big, SDL_ScaleModeLinear);
    SDL_GameController *pad = NULL;
    SDL_AudioDeviceID adev = 0;
    ANDROID_STEP(ren ? "renderer ok, audio" : "no renderer, audio");
    if (SDL_InitSubSystem(SDL_INIT_AUDIO) == 0) {
        SDL_AudioSpec want, have; SDL_zero(want); want.freq = 44100; want.format = AUDIO_S16SYS; want.channels = 2; want.samples = 1024;
        adev = SDL_OpenAudioDevice(NULL, 0, &want, &have, 0);
        if (adev) SDL_PauseAudioDevice(adev, 0);
    }
    adev_global = adev;
    for (int i = 0; i < SDL_NumJoysticks() && !pad; i++) if (SDL_IsGameController(i)) pad = SDL_GameControllerOpen(i);
    ANDROID_STEP("settings, menu");
    settings_load(&S_);
    {   /* the pre-start menu: skipped with AMIGO_NOMENU=1 (the automatic gate checks) or when switched off in it;
         * holding Shift or Back while the game starts shows it anyway */
        const char *nm = getenv("AMIGO_NOMENU");
        SDL_PumpEvents();
        int force = (SDL_GetModState() & KMOD_SHIFT) || pad_btn(pad, SDL_CONTROLLER_BUTTON_BACK);
        (void)force;   /* Karl, 14 Oct: the pre-start menu shows at every start (30 s, then the game starts) */
        if (!(nm && *nm == '1')) { if (menu_run(win, ren, &S_, 0, &pad, &aspect43)) { SDL_Quit(); return 0; } }
        else apply_settings(win, ren, &S_, &aspect43);
    }
    int kbj[5] = {0, 0, 0, 0, 0};     /* joystick state from the PC keyboard */
    /* Timing: fixed timestep accumulator (one emulated Amiga frame = exactly 20 ms PAL), decoupled from the
     * display's refresh. The game's own timing (VBlank waits, CIA timers, frame counters) runs unchanged inside the
     * emulated frame, so it never sees a variable delta. If the host falls behind, frames are run without being
     * shown until it catches up; a stall over 250 ms (window dragged, app switched) is dropped rather than
     * replayed at high speed. SDL2 already sets the Windows timer resolution to 1 ms (SDL_HINT_TIMER_RESOLUTION). */
    const double step = 0.020;
    const double pfreq = (double)SDL_GetPerformanceFrequency();
    double acc = 0.0, last = (double)SDL_GetPerformanceCounter() / pfreq;
    ANDROID_STEP("game running (menu closed)");   /* device runs grep logcat for this line */
#endif
    for (int fr = 0; frames < 0 || fr < frames; fr++) {
        while (si < ns && (sframe[si] < SCRIPT_ANCHOR ? sframe[si] <= fr : (hle_last_load_frame && (long)(hle_last_load_frame + (uint64_t)(sframe[si] - SCRIPT_ANCHOR)) <= fr))) {
            const char *k = skeys[si];
            if (k[0] == 'K' || k[0] == 'P' || k[0] == 'Q') {   /* kbfix (Cowork 17 Oct), as harness.c: raw Amiga keycode in hex: K = tap (down+up), P = down, Q = up; K01 = '1', K44 = Return, K40 = space */
                uint8_t rk = (uint8_t)(strtoul(k + 1, NULL, 16) & 0x7f);
                if (k[0] != 'Q') kbd_push(rk, 1);
                if (k[0] != 'P') kbd_push(rk, 0);
                si++; continue;
            }
            joy_up = !!strchr(k, 'U'); joy_down = !!strchr(k, 'D'); joy_left = !!strchr(k, 'L');
            joy_right = !!strchr(k, 'R');
            { int nf = !!strchr(k, 'F'); static const char *fk; static int fki;
              if (!fki) { fki = 1; fk = getenv("GNG_FIREKEY"); }
              if (fk && nf != joy_fire) kbd_push((uint8_t)strtol(fk, NULL, 16), nf);
              joy_fire = nf; }
            if (strchr(k, 'S')) { kbd_push(0x40, 1); kbd_push(0x40, 0); }
            for (const char *q = k; *q; q++) if (*q >= '1' && *q <= '8') { kbd_push((uint8_t)(0x50 + (*q - '1')), 1); kbd_push((uint8_t)(0x50 + (*q - '1')), 0); }     /* script keys 1-8 = F1-F8 (the keyboard start path) */
            { extern uint16_t mouse_joy0dat, amigo_potgor_clear; extern int mouse_lmb;   /* g39 mouse-port tokens, as harness.c: V left, W right, X port-2 2nd button, M move +10/+10 */
              static int g39m = -1; if (g39m < 0) { g39m = 0; for (int j = 0; j < ns; j++) if (strpbrk(skeys[j], "VWXM") && !strchr("KPQ", skeys[j][0])) g39m = 1; }
              if (g39m) { mouse_lmb = !!strchr(k, 'V'); amigo_potgor_clear = strchr(k, 'W') ? 0x0400 : 0; joy_fire2 = !!strchr(k, 'X');
                if (strchr(k, 'M')) mouse_joy0dat = (uint16_t)(((((mouse_joy0dat >> 8) + 10) & 0xff) << 8) | (((mouse_joy0dat & 0xff) + 10) & 0xff)); } }
            si++;
        }
#ifndef NO_SDL
        SDL_Event e; int quit = 0;
        while (SDL_PollEvent(&e)) {
            if (e.type == SDL_QUIT) quit = 1;
            else if (e.type == SDL_CONTROLLERDEVICEADDED && !pad) pad = SDL_GameControllerOpen(e.cdevice.which);
            else if (osk_event(&e)) {}
            else if ((e.type == SDL_KEYDOWN || e.type == SDL_KEYUP) && !e.key.repeat) {
                int dn = e.type == SDL_KEYDOWN;
                switch (e.key.keysym.sym) {
                case SDLK_UP: kbj[0] = dn; break; case SDLK_DOWN: kbj[1] = dn; break;
                case SDLK_LEFT: kbj[2] = dn; break; case SDLK_RIGHT: kbj[3] = dn; break;
                case SDLK_LCTRL: case SDLK_RCTRL: kbj[4] = dn; break;
                case SDLK_F9: if (dn && menu_run(win, ren, &S_, 1, &pad, &aspect43)) quit = 1;
                              last = (double)SDL_GetPerformanceCounter() / pfreq; acc = 0; break;
                case SDLK_F12: if (dn) { if (e.key.keysym.mod & KMOD_SHIFT) reccap_button(); else reccap_shot(); } break;   /* captures folder: reccap.c */
                case SDLK_F10: if (dn) { aspect43 = !aspect43; S_.aspect43 = aspect43; } break;
                case SDLK_F11: if (dn) { Uint32 fl = SDL_GetWindowFlags(win); SDL_SetWindowFullscreen(win, (fl & SDL_WINDOW_FULLSCREEN_DESKTOP) ? 0 : SDL_WINDOW_FULLSCREEN_DESKTOP); } break;
                default: { int k = sdl_to_amiga(e.key.keysym.scancode); if (k >= 0) gk_key(k, dn, SRC_KBD); } break;
                }
            }
        }
        if (quit) break;
        {   /* controllers (menu.c finds them itself) and the PC keyboard's joystick keys */
            int r = pad_apply(pad, &S_, kbj);
            if (r == 2) osk_toggle();
            if (r == 1) { if (menu_run(win, ren, &S_, 1, &pad, &aspect43)) break;
                          last = (double)SDL_GetPerformanceCounter() / pfreq; acc = 0; }
        }
#endif
        run_frame();
#ifndef NO_SDL
        osk_frame();
#endif
#ifndef AMIGO_RELEASE   /* diagnostics: harness/G3 debugging only, compiled out of release builds (Gemini review item, Karl 23:58); env read once */
        { static int dinit; static FILE *hl, *rt; static long regdump = -1, rf = -1; static const char *rfile;
          if (!dinit) { dinit = 1; if (getenv("HASHLOG")) hl = fopen(getenv("HASHLOG"), "w"); if (getenv("RAMTRACE")) rt = fopen(getenv("RAMTRACE"), "wb");
                        if (getenv("REGDUMP")) regdump = atol(getenv("REGDUMP")); if (getenv("RAMDUMP_FRAME")) rf = atol(getenv("RAMDUMP_FRAME")); rfile = getenv("RAMDUMP_FILE"); }
          if (hl) fprintf(hl, "%d %016llx %016llx\n", fr + 1, (unsigned long long)hash_frame(), (unsigned long long)hash_ram());
#ifdef AMIGO_TICKPC
          if (tickpc_f) fprintf(tickpc_f, "%d %06X\n", fr + 1, (unsigned)native_pc());
#endif
  if (regdump == fr + 1) fprintf(stderr, "BPLCON0 %04X BPLCON1 %04X BPLCON2 %04X DDF %04X-%04X DIW %04X-%04X DMACON %04X\n", custom[0x80], custom[0x81], custom[0x82], custom[0x49], custom[0x4a], custom[0x47], custom[0x48], dmacon);
          if (rt) fwrite(slowram + 0x18000, 1, 0x2000, rt);
          if (rf == fr + 1 && rfile) { FILE *o = fopen(rfile, "wb"); if (o) { fwrite(slowram, 1, SLOW_SIZE, o); fwrite(chipram, 1, CHIP_SIZE, o); fclose(o); } } }
        {   /* STATELOG=file STATEADDR=hex,...: game variables per tick (the judge's state-variable check), same format as the harness */
            static FILE *sf; static int si; static unsigned addr[64]; static int na;
            if (!si) { si = 1; const char *e = getenv("STATELOG"), *ad = getenv("STATEADDR"); if (e && ad) { sf = fopen(e, "w"); char *c = strdup(ad); for (char *t = strtok(c, ","); t && na < 64; t = strtok(NULL, ",")) addr[na++] = (unsigned)strtoul(t, 0, 16);
                fprintf(sf, "tick"); for (int i = 0; i < na; i++) fprintf(sf, " %04X", addr[i]); fprintf(sf, "\n"); } }
            if (sf) { fprintf(sf, "%d", fr + 1); for (int i = 0; i < na; i++) fprintf(sf, " %02X", chipram[addr[i] & 0x7ffff]); fprintf(sf, "\n"); }
        }
#endif
        if (wav) { fwrite(audio_buf, 4, (size_t)audio_len, wav); wavbytes += (uint32_t)audio_len * 4; }
#ifndef NO_SDL
        if (adev && SDL_GetQueuedAudioSize(adev) < 44100 * 4 / 5) {
            /* volume and stereo width (the Amiga's channels are hard left/right; 100% keeps that) */
            static int16_t ob[16384 * 2];
            float g = S_.volume / 100.0f, w = S_.stereo / 100.0f, a = 0.5f + w / 2, b = 0.5f - w / 2;
            for (int i = 0; i < audio_len; i++) {
                float L = audio_buf[i * 2], R = audio_buf[i * 2 + 1];
                float l = (L * a + R * b) * g, r = (R * a + L * b) * g;
                ob[i * 2] = (int16_t)(l > 32767 ? 32767 : l < -32768 ? -32768 : l);
                ob[i * 2 + 1] = (int16_t)(r > 32767 ? 32767 : r < -32768 ? -32768 : r);
            }
            SDL_QueueAudio(adev, ob, (Uint32)audio_len * 4);
        }
#endif
#ifndef NO_SDL
        reccap_frame(framebuf, audio_buf, audio_len);   /* nothing to do unless capturing */
#endif
        audio_len = 0;
        if (dumpdir) { char p[512]; snprintf(p, sizeof p, "%s/p%05d.%s", dumpdir, fr + 1, amigo_img_ext()); save_shot(p); }
#ifndef NO_SDL
        {
            double now = (double)SDL_GetPerformanceCounter() / pfreq;
            acc += now - last; last = now;
            if (acc > 0.25) acc = 0.25;          /* spiral-of-death guard */
            acc -= step;                          /* this emulated frame */
            static Uint32 last_present;
            if (acc < step || SDL_GetTicks() - last_present > 100) {   /* not behind by a whole frame, or 100 ms since the last one: show it */
                last_present = SDL_GetTicks();
                SDL_UpdateTexture(tex, NULL, framebuf, SCR_W * 4);
                fe_present(ren, tex, big);   /* scaling mode and filter (menu.c): presentation only, framebuf is never changed */
                ui_overlay(ren);   /* on-screen keyboard, touch keyboard button, capture indicator: screen pixels, after scaling (menu.c) */
                SDL_RenderPresent(ren);
            }
            if (acc < 0 && !vsync) SDL_Delay((Uint32)(-acc * 1000.0));
        }
#endif
    }
#ifndef NO_SDL
    reccap_close();
#endif
#ifdef AMIGO_TICKPC
    if (tickpc_f) { fclose(tickpc_f); tickpc_f = NULL; }
#endif
    if (shot) save_shot(shot);
    if (wav) {
        uint8_t h[44]; uint32_t sr = 44100, br = 44100 * 4, rs = 36 + wavbytes;
        memcpy(h, "RIFF", 4); memcpy(h + 4, &rs, 4); memcpy(h + 8, "WAVEfmt ", 8);
        uint32_t f16 = 16; uint16_t pcm = 1, chn = 2, ba = 4, bps = 16;
        memcpy(h + 16, &f16, 4); memcpy(h + 20, &pcm, 2); memcpy(h + 22, &chn, 2); memcpy(h + 24, &sr, 4); memcpy(h + 28, &br, 4);
        memcpy(h + 32, &ba, 2); memcpy(h + 34, &bps, 2); memcpy(h + 36, "data", 4); memcpy(h + 40, &wavbytes, 4);
        fseek(wav, 0, SEEK_SET); fwrite(h, 1, 44, wav); fclose(wav);
    }
    if (stats) {
        FILE *o = stdout;
        fprintf(o, "translated_instructions_executed %llu\ninterpreted_instructions_executed %llu\ninterp_calls %llu\n",
                (unsigned long long)ICNT, (unsigned long long)stat_interp_instr, (unsigned long long)stat_interp_calls);
        double tot = (double)ICNT + (double)stat_interp_instr;
        fprintf(o, "interpreter_share %.6f%%\n", tot > 0 ? 100.0 * (double)stat_interp_instr / tot : 0.0);
        for (int i = 0; i < n_interp_pcs; i++) fprintf(o, "interp_pc %06X\n", interp_pcs[i]);
        { extern int wild_jump_seen, wild_jump_interp, wild_jump_rom; extern uint32_t wild_jump_to, wild_jump_from, wild_jump_chunk; extern unsigned long long wild_jump_tick;
          if (wild_jump_seen) fprintf(o, "%s from %06X to %08X at tick %llu via %s last_chunk %06X\n", wild_jump_rom ? "rom_call" : "wild_jump", (unsigned)(wild_jump_from & 0xffffff),
                                      (unsigned)wild_jump_to, wild_jump_tick, wild_jump_interp ? "interp" : "dispatch", (unsigned)wild_jump_chunk); }
    }
#ifndef NO_SDL
    SDL_Quit();
#endif
    return 0;
}
