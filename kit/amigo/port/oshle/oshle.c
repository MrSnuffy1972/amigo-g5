    while (*i < n && d[*i] != '\n' && d[*i] != '\r') { if (k < sizeof line - 1) line[k++] = (char)d[*i]; (*i)++; }
    while (*i < n && (d[*i] == '\n' || d[*i] == '\r')) (*i)++;
    line[k] = 0; out[0] = 0; word[0] = 0;
    char *sc = strchr(line, ';'); if (sc) *sc = 0;
    char *p = dos_skip(line);
    while (!strncasecmp(p, "run ", 4) || !strncasecmp(p, "run\t", 4) || !strncasecmp(p, "c:run ", 6)) p = dos_skip(p + (p[0] == 'c' || p[0] == 'C' ? 6 : 4));
    size_t o = 0; char *q = p;
    while (*q) { q = dos_skip(q); if (!*q) break; char *e = q; while (*e && *e != ' ' && *e != '\t') e++;
        if (*q != '>' && *q != '<') { if (o) out[o++] = ' '; while (q < e && o < outsz - 1) out[o++] = *q++; }
        q = e; }
    out[o] = 0;
    if (!out[0]) return 0;
    char w[80]; size_t wl = 0; while (out[wl] && out[wl] != ' ' && wl < sizeof w - 1) { w[wl] = (char)tolower((unsigned char)out[wl]); wl++; } w[wl] = 0;
